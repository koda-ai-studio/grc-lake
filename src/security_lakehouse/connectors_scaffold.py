"""Generate a working, read-only connector skeleton for the in-repo registry.

``grc-lake connectors scaffold`` writes a collector module, a synthetic fixture,
a real test file and a Preview catalog row. The generated collector already
pages on a fixed host, honors ``Retry-After``, turns denied or incomplete reads
into collection-gap rows and emits ``observed`` evidence only, so a contributor
replaces the vendor endpoint and field mapping instead of the safety plumbing.
Nothing generated can produce a passing verdict until a person maps fields to
an outcome and binds a safeguard.
"""

