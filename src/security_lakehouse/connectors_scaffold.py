def _insert_registry(runner_path: Path, *, connector_id: str, slug: str, builder: str) -> None:
    text = runner_path.read_text(encoding="utf-8")
    start = text.find(_REGISTRY_ANCHOR)
    end = text.find("\n}\n", start)
    if start < 0 or end < 0:
        raise ValueError(f"{runner_path.name} has no REGISTRY block to extend")
    if f'"{connector_id}":' in text[start:end] or f"def _build_{slug}(" in text:
        raise ValueError(f"connector {connector_id!r} is already registered in {runner_path.name}")
    registry = text[start:end] + f'\n    "{connector_id}": _build_{slug},'
    runner_path.write_text(text[:start] + builder + registry + text[end:], encoding="utf-8")


def _json_row(row: dict[str, Any]) -> str:
    """A connectors-array row as prettier prints it: arrays stay inline when they fit in 80 columns."""
    lines = ["    {"]
    for index, (key, value) in enumerate(row.items()):
        comma = "," if index < len(row) - 1 else ""
        inline = f"      {json.dumps(key)}: {json.dumps(value, ensure_ascii=False)}{comma}"
        if isinstance(value, list) and value and len(inline) > 80:
            items = [f"        {json.dumps(item, ensure_ascii=False)}" for item in value]
            lines += [f"      {json.dumps(key)}: [", ",\n".join(items), f"      ]{comma}"]
        else:
            lines.append(inline)
    return "\n".join([*lines, "    }"])


def _append_json_row(path: Path, key: str, row: dict[str, Any]) -> None:
    text = path.read_text(encoding="utf-8")
    if row[key] in {item.get(key) for item in json.loads(text)["connectors"]}:
        raise ValueError(f"connector {row[key]!r} is already in {path.name}")
    closing = text.rstrip().rfind("]")
    last = text.rfind("}", 0, closing)
    if closing < 0 or last < 0:
        raise ValueError(f"{path} does not end with a connectors array")
    block = _json_row(row)
    updated = text[: last + 1] + ",\n" + block + text[last + 1 :]
    json.loads(updated)
    path.write_text(updated, encoding="utf-8")


def _append_to_set_literal(path: Path, name: str, value: str) -> bool:
    text = path.read_text(encoding="utf-8")
    start = text.find(f"{name} = {{\n")
    end = text.find("\n}\n", start)
    if start < 0 or end < 0:
        return False
    if f'"{value}",' not in text[start:end]:
        path.write_text(text[:end] + f'\n    "{value}",' + text[end:], encoding="utf-8")
    return True


def _ts_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _ts_prop(indent: int, key: str, value: str) -> str:
    """One property as prettier prints it: break after the colon past 80 columns unless the key is short."""
    pad = " " * indent
    line = f"{pad}{key}: {value},"
    if len(line) > 80 and len(key) > 4:
        return f"{pad}{key}:\n{pad}  {value},"
    return line


def _console_blocks(connector_id: str, *, title: str, vendor: str, kind: Kind, slug: str) -> dict[str, str]:
    rest = kind == "rest"
    key = _ts_string(connector_id)
    mark = (re.sub(r"[^A-Za-z0-9]", "", vendor)[:2] or "CX").upper()
    if rest:
        field = {
            "name": "credential_ref",
            "label": "API token env var",
            "placeholder": slug.upper() + "_API_TOKEN",
            "hint": f"Read-only {vendor} API token, stored as a secret reference. Do not paste the token.",
        }
    else:
        field = {
            "name": "lake_path",
            "label": "Export file or directory",
            "placeholder": "/srv/grc-lake/exports",
            "hint": "Absolute path under the server's allowed local root. CSV with the documented columns.",
        }
    field_lines = [_ts_prop(8, name, _ts_string(value)) for name, value in field.items() if name != "hint"]
    field_lines += ["        required: true,", _ts_prop(8, "hint", _ts_string(field["hint"]))]
    visual = {
        "vendor": vendor,
        "mark": mark,
        "accent": "#475569",
        "bg": "#f1f5f9",
        "categoryLabel": "Vendor API" if rest else "Evidence export",
    }
    preset = {
        "connectorId": connector_id,
        "title": title,
        "authLabel": "Read-only API token" if rest else "Local export path",
    }
    preset_tail = {
        "summary": f"Collects read-only {vendor} evidence as observed rows for review.",
        "providerSetup": f"Create a read-only {vendor} API token."
        if rest
        else f"Schedule the {vendor} CSV export into the allowed local root.",
        "trustOpsInput": "API token reference." if rest else "Export file or directory path.",
        "advancedTitle": "What is collected",
    }
    details = [
        f"Every row is observed until the {vendor} fields are mapped to an outcome; nothing passes by default.",
        "Denied, incomplete or empty reads are recorded as collection gaps, never as a pass.",
    ]
    badges = f"[{_ts_string('Read-only' if rest else 'CSV export')}, {_ts_string('Preview')}]"
    preset_lines = [_ts_prop(4, name, _ts_string(value)) for name, value in preset.items()]
    preset_lines.append(_ts_prop(4, "badges", badges))
    preset_lines += [_ts_prop(4, name, _ts_string(value)) for name, value in preset_tail.items()]
    preset_lines += ["    advancedDetails: [", *(f"      {_ts_string(line)}," for line in details), "    ],"]
    return {
        "forms": "\n".join([f"    {key}: [", "      {", *field_lines, "      },", "    ],"]),
        "visuals": "\n".join(
            [f"  {key}: {{", *(_ts_prop(4, name, _ts_string(value)) for name, value in visual.items()), "  },"]
        ),
        "presets": "\n".join([f"  {key}: {{", *preset_lines, "  },"]),
    }


def _insert_before_close(path: Path, anchor: str, closer: str, block: str) -> bool:
    text = path.read_text(encoding="utf-8")
    start = text.find(anchor)
    end = text.find(closer, start)
    if start < 0 or end < 0:
        return False
    path.write_text(text[:end] + "\n" + block + text[end:], encoding="utf-8")
    return True


def _write_new(path: Path, content: str) -> None:
    if path.exists():
        raise ValueError(f"{path} already exists")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="")


def scaffold_connector(
    connector_id: str,
    *,
    title: str | None = None,
    vendor: str | None = None,
    kind: Kind = "rest",
    output_dir: str | Path | None = None,
    into_tree: str | Path | None = None,
) -> dict[str, Any]:
    """Write a working connector skeleton.

    With ``output_dir`` the files are staged there (``src/``, ``tests/`` and a
    ``catalog-entry.json``). With ``into_tree`` they are written into a
    repository checkout, the catalog row is appended and the runner registry is
    extended, refusing to overwrite anything that already exists.
    """
    slug = _slugify(connector_id)
    if not slug or not re.fullmatch(r"[a-z][a-z0-9_]*", slug):
        raise ValueError("connector_id must start with a letter and contain alphanumeric characters")
    if kind not in SCAFFOLD_KINDS:
        raise ValueError(f"kind must be one of {', '.join(SCAFFOLD_KINDS)}")
    if (output_dir is None) == (into_tree is None):
        raise ValueError("pass exactly one of output_dir or into_tree")
    title = title or connector_id.replace("-", " ").title()
    vendor = vendor or title
    context = {
        "CONNECTOR_ID": connector_id,
        "SLUG": slug,
        "SLUG_HOST": slug.replace("_", "-"),
        "CLASS": _class_name(connector_id),
        "TITLE": title,
        "VENDOR": vendor,
        "ENV": f"{slug.upper()}_API_TOKEN",
    }
    rest = kind == "rest"
    base = Path(into_tree if into_tree is not None else output_dir)  # type: ignore[arg-type]
    module_path = base / "src" / "security_lakehouse" / f"connectors_{slug}.py"
    test_path = base / "tests" / f"test_{slug}_connector.py"
    fixture_path = base / "tests" / "fixtures" / slug / ("items.json" if rest else "export.csv")
    entry = _catalog_entry(connector_id, title=title, vendor=vendor, kind=kind, slug=slug)
    builder = _render(_REST_BUILDER if rest else _EXPORT_BUILDER, context)
    if into_tree is not None:
        catalog_path = base / "connectors" / "catalog.json"
        runner_path = base / "src" / "security_lakehouse" / "connector_runner.py"
        known = {row["connector_id"] for row in json.loads(catalog_path.read_text(encoding="utf-8"))["connectors"]}
        if connector_id in known:
            raise ValueError(f"connector {connector_id!r} is already in the catalog")
        for path in (module_path, test_path, fixture_path):
            if path.exists():
                raise ValueError(f"{path} already exists")
    wired: list[str] = []
    for path, content in (
        (module_path, _render(_REST_MODULE if rest else _EXPORT_MODULE, context)),
        (test_path, _render(_REST_TEST if rest else _EXPORT_TEST, context)),
        (fixture_path, json.dumps(_REST_FIXTURE, indent=2) + "\n" if rest else _EXPORT_FIXTURE),
    ):
        _write_new(path, content)
    if into_tree is not None:
        _append_json_row(catalog_path, "connector_id", entry)
        wired.append(str(catalog_path))
        _insert_registry(runner_path, connector_id=connector_id, slug=slug, builder=builder)
        wired.append(str(runner_path))
        evidence_path = base / "docs" / "qualification" / "connector-evidence.json"
        if evidence_path.is_file():
            qualification = {
                "connector_id": connector_id,
                "fixture_tests": [f"tests/{test_path.name}"],
                "live_record": None,
                "owner": None,
            }
            _append_json_row(evidence_path, "connector_id", qualification)
            wired.append(str(evidence_path))
        lib = base / "app" / "web" / "src" / "lib"
        blocks = _console_blocks(connector_id, title=title, vendor=vendor, kind=kind, slug=slug)
        for file_name, anchor, closer, block in (
            ("connector-forms.ts", "export const CONNECTOR_CREDENTIAL_FIELDS", "\n  };\n", blocks["forms"]),
            ("connector-visuals.ts", "export const CONNECTOR_VISUALS", "\n};\n", blocks["visuals"]),
            ("integration-presets.ts", "const PRESETS:", "\n};\n", blocks["presets"]),
        ):
            target = lib / file_name
            if target.is_file() and _insert_before_close(target, anchor, closer, block):
                wired.append(str(target))
        registry_test = base / "tests" / "test_connector_registry.py"
        if registry_test.is_file():
            for name in ("REAL_ADAPTERS", "PREVIEW_CONNECTORS"):
                if _append_to_set_literal(registry_test, name, connector_id):
                    wired.append(f"{registry_test}:{name}")
        catalog_entry_path = catalog_path
    else:
        catalog_entry_path = base / "catalog-entry.json"
        catalog_entry_path.write_text(json.dumps(entry, indent=2) + "\n", encoding="utf-8")
        (base / "registry-builder.py").write_text(builder, encoding="utf-8")
    module = module_path.name
    return {
        "connector_id": connector_id,
        "kind": kind,
        "into_tree": into_tree is not None,
        "wired": wired,
        "module_path": str(module_path),
        "test_path": str(test_path),
        "fixture_path": str(fixture_path),
        "catalog_entry_path": str(catalog_entry_path),
        "registry_line": f'    "{connector_id}": _build_{slug},',
        "catalog_flag": '"is_implemented": true',
        "next_steps": [
            *(
                []
                if into_tree is not None
                else [
                    "Rerun with --into-tree from a repository checkout to wire everything below automatically, or "
                    + "move src/ and tests/ into the repository, append catalog-entry.json to connectors/catalog.json, "
                    + "add registry-builder.py plus the registry line to src/security_lakehouse/connector_runner.py, "
                    + "add a docs/qualification/connector-evidence.json row and the id to REAL_ADAPTERS and "
                    + "PREVIEW_CONNECTORS in tests/test_connector_registry.py."
                ]
            ),
            f"Replace every TODO(vendor) in {module} with values from {vendor}'s official API reference; "
            + "keep reads GET-only on the fixed host.",
            "Map vendor fields to pass/open/not_evaluated and bind a safeguard whose asset_types accept "
            + "the asset; leave rows observed until you do. Do not edit safeguard definitions.",
            f"Grow tests/{test_path.name} (429 Retry-After, page budget, malformed page) and keep the "
            + "fixture synthetic.",
            "Review the console entries in app/web/src/lib/connector-visuals.ts, connector-forms.ts and "
            + "integration-presets.ts (added by --into-tree) and run npm --prefix app/web run typecheck.",
            "Raise the Preview count pinned in tests/test_connector_qualification_doc.py by one.",
            "Document permissions and setup in docs/CONNECTORS.md, add a CHANGELOG line under Unreleased, "
            + "then run make connector-qualification-doc and make readme-header (both regenerate committed files).",
            f"Run: uv run python -m pytest -q tests/{test_path.name} && grc-lake connectors validate",
        ],
    }
