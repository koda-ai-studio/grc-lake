CONNECTOR_ID = "__CONNECTOR_ID__"
SOURCE = "__SLUG__"
EVENT_TYPE = f"{SOURCE}.item"
GAP_EVENT_TYPE = f"{SOURCE}.collection_gap"
# TODO(vendor): an asset type the target safeguard's ``asset_types`` accepts.
ASSET_TYPE = "service"
# TODO(vendor): the documented API host. Never accept a caller-supplied URL.
API_HOST = "api.__SLUG_HOST__.example"
# TODO(vendor): the documented read-only list endpoint.
ITEMS_PATH = "/v1/items"
TOKEN_ENV = "__ENV__"
API_LABEL = "__VENDOR__ API"
PAGE_LIMIT = 100
DEFAULT_TIMEOUT = 30
DEFAULT_MAX_PAGES = 200
# Only these vendor fields are stored; never keep free text, secrets or payloads.
KEPT_FIELDS = ("name", "status")


class __CLASS__Client:
    """Read-only client: GET requests on the fixed host only."""

    def __init__(self, *, token: str, timeout: int = DEFAULT_TIMEOUT, max_pages: int = DEFAULT_MAX_PAGES) -> None:
        self.host = API_HOST
        self.timeout = timeout
        self.max_pages = max_pages
        self._token = token

    def __repr__(self) -> str:
        return f"__CLASS__Client(host={self.host!r})"

    def items(self) -> list[dict[str, Any]]:
        def fetch_page(cursor: str | None) -> dict[str, Any]:
            query = {"limit": str(PAGE_LIMIT)}
            if cursor:
                query["cursor"] = cursor  # TODO(vendor): the documented cursor parameter
            return self._get(ITEMS_PATH, query)

        return list(paginate(fetch_page, _items, _next_cursor, max_pages=self.max_pages))

    def _get(self, path: str, query: dict[str, str]) -> dict[str, Any]:
        request = urllib.request.Request(
            f"https://{self.host}{path}?{urllib.parse.urlencode(query)}",
            method="GET",
            headers={
                "Accept": "application/json",
                "Authorization": f"Bearer {self._token}",  # TODO(vendor): the documented auth header
                "User-Agent": "grc-lake",
            },
        )
        try:
            payload = backoff.http_retry(lambda: self._open(request))
        except urllib.error.HTTPError as exc:
            raise _http_failure(exc.code) from None
        if not isinstance(payload, dict):
            raise ValueError(f"{API_LABEL} collection incomplete: expected a JSON object")
        return payload

    def _open(self, request: urllib.request.Request) -> Any:
        with netguard.open_public(request, timeout=self.timeout, label=CONNECTOR_ID) as response:
            return read_json_response(response)


class __CLASS__FixtureClient:
    """Offline client backed by ``items.json`` (one API page) in a fixture directory."""

    def __init__(self, fixture_dir: str | Path) -> None:
        self.fixture = Path(fixture_dir)
        self.host = API_HOST

    def items(self) -> list[dict[str, Any]]:
        payload = read_json(self.fixture / "items.json")
        return _items(payload if isinstance(payload, dict) else {"items": payload})


def collect___SLUG___evidence(
    client: __CLASS__Client | __CLASS__FixtureClient,
    *,
    collected_at: datetime | None = None,
    tenant_id: str = "customer-managed",
) -> list[dict[str, Any]]:
    """Collect ``observed`` rows, or one collection-gap row when the read is incomplete."""
    now = collected_at or datetime.now(UTC)
    synthetic = isinstance(client, __CLASS__FixtureClient)
    try:
        items = client.items()
    except CollectionGapError as gap:
        return [_gap_event(gap.attributes(), now=now, tenant_id=tenant_id, synthetic=synthetic)]
    except IncompleteCollectionError:
        attributes = {"reason": "page_budget_exhausted", "collection": "items", "api": API_LABEL}
        return [_gap_event(attributes, now=now, tenant_id=tenant_id, synthetic=synthetic)]
    if not items:
        # An empty success is never evidence of absence.
        attributes = {"reason": "empty_collection", "collection": "items", "api": API_LABEL}
        return [_gap_event(attributes, now=now, tenant_id=tenant_id, synthetic=synthetic)]
    return [_item_event(item, now=now, tenant_id=tenant_id, synthetic=synthetic) for item in items]


def _http_failure(code: int) -> Exception:
    if code == 401:
        return ConnectorAccessError(f"{API_LABEL} rejected the API token (HTTP 401); check the token and its scope")
    if code in {403, 404}:
        return CollectionGapError(
            f"{API_LABEL} items were not collected (HTTP {code})",
            collection="items",
            reason="permission_denied" if code == 403 else "not_found",
            api=API_LABEL,
        )
    return ConnectorAccessError(f"{API_LABEL} request failed (HTTP {code})")


def _items(page: dict[str, Any]) -> list[dict[str, Any]]:
    return object_rows(page.get("items"), label=API_LABEL)  # TODO(vendor): the documented list field


def _next_cursor(page: dict[str, Any]) -> str | None:
    link = page.get("next")  # TODO(vendor): the documented next-page field
    if not link:
        return None
    if not isinstance(link, str):
        raise ValueError(f"{API_LABEL} collection incomplete: malformed next-page value")
    if "://" not in link and not link.startswith("/"):
        return link
    parts = urllib.parse.urlsplit(link)
    if parts.netloc and parts.netloc != API_HOST:
        raise ValueError(f"{API_LABEL} pagination link left {API_HOST}; collection stopped")
    values = urllib.parse.parse_qs(parts.query).get("cursor") or []
    if len(values) != 1 or not values[0]:
        raise ValueError(f"{API_LABEL} collection incomplete: next-page link without a cursor")
    return values[0]


def _item_event(item: dict[str, Any], *, now: datetime, tenant_id: str, synthetic: bool) -> dict[str, Any]:
    item_id = str(item.get("id") or "").strip()
    if not item_id:
        raise ValueError(f"{API_LABEL} collection incomplete: an item has no id")
    attributes: dict[str, Any] = {"item_id": item_id, "synthetic": synthetic}
    attributes.update({f"vendor_{key}": item.get(key) for key in KEPT_FIELDS if key in item})
    return _event(
        key=item_id,
        event_type=EVENT_TYPE,
        entity={
            "asset_id": f"{SOURCE}:{item_id}",
            "asset_type": ASSET_TYPE,
            "asset_owner": SOURCE,
            "environment": "prod",
            "org": SOURCE,
        },
        attributes=attributes,
        evidence_ref=f"https://{API_HOST}{ITEMS_PATH}/{urllib.parse.quote(item_id, safe='')}",
        now=now,
        tenant_id=tenant_id,
    )


def _gap_event(attributes: dict[str, Any], *, now: datetime, tenant_id: str, synthetic: bool) -> dict[str, Any]:
    collection = str(attributes.get("collection") or "items")
    return _event(
        key=f"gap:{collection}",
        event_type=GAP_EVENT_TYPE,
        entity={
            "asset_id": f"{SOURCE}:collection:{collection}",
            "asset_type": "collection_scope",
            "asset_owner": SOURCE,
            "environment": "prod",
            "org": SOURCE,
        },
        attributes={**attributes, "synthetic": synthetic},
        evidence_ref=f"https://{API_HOST}{ITEMS_PATH}",
        now=now,
        tenant_id=tenant_id,
        severity="low",
        status="not_evaluated",
    )


def _event(
    *,
    key: str,
    event_type: str,
    entity: dict[str, Any],
    attributes: dict[str, Any],
    evidence_ref: str,
    now: datetime,
    tenant_id: str,
    severity: str = "info",
    status: str = "observed",
) -> dict[str, Any]:
    stable = stable_id_slug(f"{event_type}:{key}", fallback=SOURCE)
    return {
        "event_id": f"{SOURCE}-{stable}",
        "tenant_id": tenant_id,
        "workspace_id": "default",
        "event_time": utc_iso(now),
        "source": SOURCE,
        "event_type": event_type,
        "entity": entity,
        "severity": severity,
        "status": status,
        "controls": [],
        "evidence": {
            "evidence_id": f"ev-{stable}",
            "evidence_ref": evidence_ref,
            "evidence_collected_at": utc_iso(now),
        },
        "attributes": attributes,
    }
