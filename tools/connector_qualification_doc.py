"""Generate built-in connector qualification pointers without inferring provider parity."""

from __future__ import annotations

import json
import re
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build_rows(catalog: list[dict], records: list[dict], *, root: Path = ROOT) -> list[dict]:
    definitions = {row["connector_id"]: row for row in catalog}
    evidence = {row["connector_id"]: row for row in records}
    if len(definitions) != len(catalog) or len(evidence) != len(records) or definitions.keys() != evidence.keys():
        raise ValueError("qualification records must match the catalog exactly, without duplicates")
    rows = []
    for connector_id, definition in sorted(definitions.items()):
        record = evidence[connector_id]
        fixtures = record.get("fixture_tests")
        if not isinstance(fixtures, list) or (definition.get("is_implemented") and not fixtures):
            raise ValueError(f"{connector_id}: executable adapters require fixture test references")
        for reference in fixtures:
            path = Path(reference)
            if (
                not path.is_relative_to("tests")
                or not (root / path).resolve().is_relative_to((root / "tests").resolve())
                or path.suffix != ".py"
                or not (root / path).is_file()
            ):
                raise ValueError(f"{connector_id}: invalid fixture test reference")
        if record.get("owner") is not None and not isinstance(record["owner"], str):
            raise ValueError(f"{connector_id}: owner must be a name or null for unassigned")
        live = record["live_record"]
        if live is not None:
            if not isinstance(live, dict) or any(
                not isinstance(live.get(key), str) or not live[key].strip()
                for key in ("date", "source_basis", "scope", "reference")
            ):
                raise ValueError(f"{connector_id}: incomplete live record")
            try:
                date.fromisoformat(live["date"])
            except ValueError as exc:
                raise ValueError(f"{connector_id}: invalid live record date") from exc
            source = root / live["reference"].split("#", 1)[0]
            if (
                not re.fullmatch(r"[0-9a-f]{7,40}", live["source_basis"])
                or not source.resolve().is_relative_to((root / "docs").resolve())
                or not source.is_file()
            ):
                raise ValueError(f"{connector_id}: invalid live record source")
        rows.append({**definition, "fixture_tests": fixtures, "owner": record["owner"], "live_record": live})
    return rows


def _text(value: object) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def render(*, root: Path = ROOT) -> str:
    catalog = json.loads((root / "connectors/catalog.json").read_text())["connectors"]
    records = json.loads((root / "docs/qualification/connector-evidence.json").read_text())["connectors"]
    rows = build_rows(catalog, records, root=root)
    lines = [
        "# Connector qualification matrix",
        "",
        "Generated by `make connector-qualification-doc`; do not edit this file directly.",
        "Catalog stages and permissions come from [the catalog](../connectors/catalog.json).",
        "Test pointers, historical records and ownership come from",
        "[the evidence index](qualification/connector-evidence.json). CI rejects catalog or document drift.",
        "",
        "This covers built-in contracts only, not installed third-party adapters. Linked test modules",
        "contain offline fixtures or mocks; their presence is not a passing test receipt or live-provider parity.",
        "Use the exact revision's CI results to establish which tests passed. Configuration boundaries",
        "do not have standalone collection adapters. An implemented or preview label does not qualify a provider.",
        "",
        "Historical live records are bounded source audits, not qualification of the current release.",
        "Their source basis can include additional audit changes; it is not an exact tested package version.",
        "No current-release live qualification is asserted by this matrix. Unassigned means no qualification",
        "owner is recorded here. Credentials, provider identities and raw live evidence stay private.",
        "",
        "The [GitHub collection contract](GITHUB_QUALIFICATION.md) details the selected adapter's",
        "pagination, errors, replay and remaining limitations. Follow-ups remain in",
        "[#908](https://github.com/koda-ai-studio/grc-lake/issues/908),",
        "[Databricks #734](https://github.com/koda-ai-studio/grc-lake/issues/734) and",
        "[KnowBe4 #737](https://github.com/koda-ai-studio/grc-lake/issues/737).",
        "",
        "## Evidence and ownership",
        "",
        "| Connector | Catalog stage | Offline test pointers | Historical live record | Qualification owner |",
        "| --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        stage = "Configuration boundary"
        if row.get("is_implemented"):
            stage = "Preview" if row.get("release_stage") == "preview" else "Implemented"
        tests = "; ".join(f"[{Path(path).stem.removeprefix('test_')}]({'../' + path})" for path in row["fixture_tests"])
        live = row["live_record"]
        record = "No scoped live record linked"
        if live:
            record = f"[{live['date']}; source basis `{live['source_basis']}`](../{live['reference']}): {_text(live['scope'])}"
        elif not row.get("is_implemented"):
            record = "Not applicable: no standalone collector"
        lines.append(
            f"| `{row['connector_id']}` | {stage} | {tests or 'Catalog validation only'} | {record} | {_text(row['owner'] or 'Unassigned')} |"
        )
    lines.extend(
        [
            "",
            "## Catalog permission boundaries",
            "",
            "These are the catalog's declared minimum permissions, not proof of access or a complete provider IAM policy.",
            "Qualify the actual principal, account, resource scope and provider version separately.",
            "",
            "| Connector | Access boundary | Declared minimum permissions |",
            "| --- | --- | --- |",
        ]
    )
    for row in rows:
        permissions = "; ".join(_text(value) for value in row["minimum_permissions"])
        lines.append(f"| `{row['connector_id']}` | `{row['access_boundary']}` | {permissions} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (ROOT / "docs/CONNECTOR_QUALIFICATION.md").write_text(render(), encoding="utf-8")
